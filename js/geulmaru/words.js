  var ROUND = 10;
  function rand(n, rng) { return Math.floor((rng || Math.random)() * n); }
  function shuffle(a, rng) {
    a = a.slice();
    for (var i = a.length - 1; i > 0; i--) { var j = rand(i + 1, rng); var t = a[i]; a[i] = a[j]; a[j] = t; }
    return a;
  }
  function bank(grade) { return Q.filter(function (q) { return q.grade === grade; }); }
  function byId(id) { return Q.filter(function (q) { return q.id === id; })[0] || null; }
  // 문제 하나를 이번 판용으로: 선택지 순서를 섞고, 섞은 뒤 정답 번호를 다시 계산
  function prepare(q, rng) {
    var order = shuffle([0, 1, 2], rng);
    return { q: q, options: order.map(function (i) { return q.options[i]; }), correct: order.indexOf(q.correctIndex) };
  }
  // 한 판: 학년 문제 은행에서 낱말이 겹치지 않게 n개(기본 10)를 무작위로 골라 순서·선택지를 섞음
  function makeRound(grade, n, rng) {
    n = n || ROUND;
    var seen = {}, pick = [];
    shuffle(bank(grade), rng).forEach(function (q) { if (pick.length < n && !seen[q.word]) { seen[q.word] = true; pick.push(q); } });
    return pick.map(function (q) { return prepare(q, rng); });
  }
  // 복습: 틀린 문제(id 목록)만 순서·선택지를 다시 섞어서
  function makeReview(ids, rng) {
    return shuffle(ids.map(byId).filter(Boolean), rng).map(function (q) { return prepare(q, rng); });
  }
  function judge(item, choice) { return choice === item.correct; }

